#!/usr/bin/env python3
r"""Turn the stored experiment artifacts into LaTeX the report can include.

``run_experiment.py`` prints its tables to the terminal and stores them as JSON.
Copying those numbers into ``report/main.tex`` by hand is slow, unreproducible
and silently wrong the moment the experiment is re-run.  This script closes the
gap: it reads ``results/<tag>_*.json`` and writes

* ``report/tables/*.tex`` -- one complete ``tabular`` per table, so the caption,
  the label and the float placement stay under the author's control in
  ``main.tex``;
* ``report/generated_macros.tex`` -- ``\\newcommand`` definitions for the numbers
  that appear in running prose (the best model's name and AUC, the fold
  strategy, the environment), so a sentence never disagrees with a table.

Usage:
    python scripts/make_report_assets.py                # tag "experiment"
    python scripts/make_report_assets.py --tag ablation
"""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config import Config  # noqa: E402
from src.repository import get_artifact_repository  # noqa: E402
from src.repository.base import DatasetNotFoundError  # noqa: E402

LOGGER = logging.getLogger("make_report_assets")

#: Written at the top of every generated file, so nobody edits one by hand.
BANNER = (
    "% Generated by scripts/make_report_assets.py -- do not edit.\n"
    "% Re-run the script instead; every number here comes from results/.\n"
)

PRETTY_MODEL = {
    "prior": "prior",
    "keyword": "keyword",
    "logreg": "logreg",
    "nbsvm": "nbsvm",
    "linear_svm": "linear\\_svm",
    "distilbert": "distilbert",
}


def escape(text: object) -> str:
    """Escape the LaTeX special characters that occur in our identifiers."""
    out = str(text)
    for char in ("\\", "&", "%", "$", "#", "_", "{", "}"):
        out = out.replace(char, "\\" + char)
    return out


def number(value: object, places: int = 4) -> str:
    """Format a float for a table cell, marking an undefined value as ---."""
    try:
        as_float = float(value)
    except (TypeError, ValueError):
        return escape(value)
    if as_float != as_float:  # NaN
        # COMINGUP warns about this: a NaN ratio must never reach the report as
        # a number, because a reader cannot tell it from a measurement.
        return "---"
    return f"{as_float:.{places}f}"


def integer(value: object) -> str:
    """Format an integer with a LaTeX thousands separator."""
    try:
        text = f"{int(round(float(value))):,}"
    except (TypeError, ValueError):
        return escape(value)
    return text.replace(",", "{,}")


def tabular(column_spec: str, header: list[str], rows: list[list[str]]) -> str:
    """Assemble a booktabs ``tabular`` from already-formatted cells."""
    lines = [
        BANNER,
        "\\begin{tabular}{" + column_spec + "}",
        "  \\toprule",
        "  " + " & ".join(header) + " \\\\",
        "  \\midrule",
    ]
    lines += ["  " + " & ".join(row) + " \\\\" for row in rows]
    lines += ["  \\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Individual tables
# --------------------------------------------------------------------------- #


def leaderboard_table(leaderboard: list[dict]) -> str:
    """Table 2: one row per model, ranked by the official metric."""
    rows = []
    for entry in leaderboard:
        rows.append(
            [
                PRETTY_MODEL.get(entry["model"], escape(entry["model"])),
                f"{number(entry['mean_column_auc_mean'])} $\\pm$ "
                f"{number(entry['mean_column_auc_std'])}",
                number(entry["mean_column_pr_auc_mean"]),
                number(entry["macro_f1_mean"]),
                number(entry["micro_f1_mean"]),
                number(entry["fit_seconds_mean"], places=1),
            ]
        )
    return tabular(
        "lccccr",
        [
            "Model",
            "Mean col.\\ AUC",
            "PR-AUC",
            "Macro $F_1$",
            "Micro $F_1$",
            "Fit (s)",
        ],
        rows,
    )


def per_label_table(result: dict) -> str:
    """Per-label metrics of the best model."""
    frame = pd.DataFrame(result["label_summary"]).loc[result["label_names"]]
    rows = []
    for label, row in frame.iterrows():
        rows.append(
            [
                escape(label),
                integer(row["support"]),
                number(row["roc_auc"]),
                number(row["pr_auc"]),
                number(row["precision"]),
                number(row["recall"]),
                number(row["f1"]),
                number(row["threshold"], places=3),
            ]
        )
    return tabular(
        "lrccccccc"[:9],
        [
            "Label",
            "Support",
            "ROC-AUC",
            "PR-AUC",
            "Prec.",
            "Recall",
            "$F_1$",
            "Thresh.",
        ],
        rows,
    )


def significance_table(significance: dict) -> str:
    """Pairwise Wilcoxon p-values, with the significant cells in bold."""
    models = significance["models"]
    p_values = significance["p_values"]
    alpha = significance["bonferroni_alpha"]

    rows = []
    for first in models:
        cells = [PRETTY_MODEL.get(first, escape(first))]
        for second in models:
            if first == second:
                cells.append("---")
                continue
            value = float(p_values[second][first])
            formatted = number(value, places=3)
            cells.append(
                "\\textbf{" + formatted + "}" if value < alpha else formatted
            )
        rows.append(cells)

    header = ["Model"] + [PRETTY_MODEL.get(name, escape(name)) for name in models]
    return tabular("l" + "c" * len(models), header, rows)


def threshold_table(result: dict) -> str:
    """Per-label F1 at 0.5 against the tuned threshold, and the gain."""
    tuned = pd.DataFrame(result["label_summary"]).loc[result["label_names"]]
    half = pd.DataFrame(result["label_summary_at_half"]).loc[result["label_names"]]

    rows = []
    for label in result["label_names"]:
        at_half = float(half.loc[label, "f1"])
        at_tuned = float(tuned.loc[label, "f1"])
        gain = at_tuned - at_half
        rows.append(
            [
                escape(label),
                number(tuned.loc[label, "threshold"], places=3),
                number(at_half),
                number(at_tuned),
                ("$+$" if gain >= 0 else "$-$") + number(abs(gain)),
            ]
        )
    return tabular(
        "lcccc",
        [
            "Label",
            "Tuned thresh.",
            "$F_1$ @ 0.5",
            "$F_1$ @ tuned",
            "Gain",
        ],
        rows,
    )


def bias_table(bias: list[dict]) -> str:
    """Identity-term false-positive rates against the background rate."""
    rows = []
    for entry in bias:
        rows.append(
            [
                escape(entry["term"]),
                integer(entry["n_comments"]),
                number(entry["positive_rate"], places=3),
                number(entry["subgroup_fpr"], places=3),
                number(entry["background_fpr"], places=3),
                number(entry["fpr_ratio"], places=2),
                number(entry["subgroup_auc"], places=3),
            ]
        )
    return tabular(
        "lrcccccc"[:8],
        [
            "Term",
            "$n$",
            "Toxic rate",
            "Subgroup FPR",
            "Background FPR",
            "Ratio",
            "Subgroup AUC",
        ],
        rows,
    )


def hierarchy_table(hierarchy: list[dict]) -> str:
    """How often binary relevance predicts a child label without ``toxic``."""
    rows = []
    for entry in hierarchy:
        rows.append(
            [
                escape(entry["label"]),
                integer(entry["predicted_positive"]),
                integer(entry["without_parent"]),
                number(100.0 * float(entry["violation_rate"]), places=2) + "\\%",
            ]
        )
    return tabular(
        "lrrr",
        ["Label", "Predicted positive", "Without \\emph{toxic}", "Rate"],
        rows,
    )


def test_set_table(leaderboard: list[dict]) -> str:
    """One row per model, scored once on Kaggle's official test set."""
    rows = [
        [
            PRETTY_MODEL.get(entry["model"], escape(entry["model"])),
            number(entry["mean_column_auc"]),
            number(entry["mean_column_pr_auc"]),
            number(entry["macro_f1"]),
            number(entry["micro_f1"]),
        ]
        for entry in leaderboard
    ]
    return tabular(
        "lcccc",
        ["Model", "Mean col.\\ AUC", "PR-AUC", "Macro $F_1$", "Micro $F_1$"],
        rows,
    )


def environment_table(metadata: dict) -> str:
    """The reproducibility subsection's software and hardware inventory."""
    rows = [
        ["Python", escape(metadata["python"])],
        ["Platform", escape(metadata["platform"])],
        ["Processor", escape(metadata["processor"])],
    ]
    rows += [
        [escape(name), escape(version)]
        for name, version in sorted(metadata["libraries"].items())
    ]
    rows.append(["Random seed", escape(metadata["seed"])])
    return tabular("ll", ["Component", "Version"], rows)


def macros(metadata: dict, leaderboard: list[dict]) -> str:
    r"""``\\newcommand`` definitions for the numbers that appear in prose."""
    best = leaderboard[0]
    runner_up = leaderboard[1] if len(leaderboard) > 1 else best
    definitions = {
        "BestModel": PRETTY_MODEL.get(best["model"], escape(best["model"])),
        "BestAUC": number(best["mean_column_auc_mean"]),
        "BestAUCStd": number(best["mean_column_auc_std"]),
        "BestPRAUC": number(best["mean_column_pr_auc_mean"]),
        "BestMacroF": number(best["macro_f1_mean"]),
        "RunnerUpModel": PRETTY_MODEL.get(
            runner_up["model"], escape(runner_up["model"])
        ),
        "RunnerUpAUC": number(runner_up["mean_column_auc_mean"]),
        "FoldStrategy": escape(metadata["fold_strategy"].replace("_", " ")),
        "NFolds": str(metadata["n_folds"]),
        "NComments": integer(metadata["n_comments"]),
        "NModels": str(len(leaderboard)),
        "RandomSeed": str(metadata["seed"]),
        "PythonVersion": escape(metadata["python"]),
        "SklearnVersion": escape(metadata["libraries"].get("sklearn", "n/a")),
        "RunTimestamp": escape(metadata["timestamp"]),
    }
    lines = [BANNER]
    lines += [
        "\\newcommand{\\" + name + "}{" + value + "}"
        for name, value in definitions.items()
    ]
    lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Driver
# --------------------------------------------------------------------------- #


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Parse the command line."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--tag", default="experiment", help="artifact prefix written by run_experiment"
    )
    parser.add_argument(
        "--backend",
        choices=["file", "memory"],
        default="file",
        help="persistence layer to read the artifacts from",
    )
    parser.add_argument(
        "--test-tag",
        default="test",
        help="artifact prefix written by evaluate_test_set",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """Entry point.  Returns a process exit code."""
    args = parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)-7s %(message)s")

    config = Config(persistence_backend=args.backend)
    artifacts = get_artifact_repository(config)

    def load(name: str) -> object | None:
        """Return an artifact, or None with a warning when it is absent."""
        try:
            return artifacts.load(f"{args.tag}_{name}")
        except DatasetNotFoundError:
            LOGGER.warning(
                "Artifact %s_%s is missing; the tables that need it are skipped.",
                args.tag,
                name,
            )
            return None

    metadata = load("metadata")
    leaderboard = load("leaderboard")
    if metadata is None or leaderboard is None:
        LOGGER.error(
            "Run `python scripts/run_experiment.py --tag %s` first: without the "
            "metadata and leaderboard artifacts there is nothing to generate.",
            args.tag,
        )
        return 1

    # A synthetic run exists to prove the pipeline is wired, not to be quoted.
    # Its AUC is an artefact of generated data being linearly separable, so
    # refuse rather than let those numbers reach the report unlabelled.  Runs
    # recorded before this flag existed fall back to inspecting the raw files.
    real_dataset = metadata.get("real_dataset")
    if real_dataset is None:
        from src.dataio import raw_files_available

        real_dataset = raw_files_available()
        LOGGER.warning(
            "This run predates the real_dataset flag; inferring %s from the "
            "files present in data/raw.",
            real_dataset,
        )
    if not real_dataset:
        LOGGER.error(
            "Run '%s' was evaluated on synthetic data. Its numbers are "
            "meaningless and will not be written to report/. Download the "
            "dataset and re-run the experiment.",
            args.tag,
        )
        return 1

    tables_dir = config.project_root / "report" / "tables"
    tables_dir.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []

    def write(relative: str, content: str) -> None:
        """Write one generated file and remember it for the summary."""
        path = config.project_root / "report" / relative
        path.write_text(content, encoding="utf-8")
        written.append(path)

    write("tables/leaderboard.tex", leaderboard_table(leaderboard))
    write("tables/environment.tex", environment_table(metadata))
    write("generated_macros.tex", macros(metadata, leaderboard))

    best = metadata["best_model"]
    best_result = load(best)
    if best_result is not None:
        write("tables/per_label.tex", per_label_table(best_result))
        write("tables/threshold_gain.tex", threshold_table(best_result))

    significance = load("significance")
    if significance is not None:
        write("tables/significance.tex", significance_table(significance))

    bias = load("bias")
    if bias:
        write("tables/bias.tex", bias_table(bias))

    hierarchy = load("hierarchy")
    if hierarchy:
        write("tables/hierarchy.tex", hierarchy_table(hierarchy))

    # Written by scripts/evaluate_test_set.py, under its own tag.
    if artifacts.exists(f"{args.test_tag}_leaderboard"):
        write(
            "tables/test_set.tex",
            test_set_table(artifacts.load(f"{args.test_tag}_leaderboard")),
        )
    else:
        LOGGER.warning(
            "No %s_leaderboard artifact; run scripts/evaluate_test_set.py to "
            "add the official test-set table.",
            args.test_tag,
        )

    for path in written:
        LOGGER.info("wrote %s", path.relative_to(config.project_root))
    LOGGER.info(
        "%d files generated from the '%s' run of %s.",
        len(written),
        args.tag,
        metadata["timestamp"],
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
